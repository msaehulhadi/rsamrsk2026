private void tampilkfa(){
    Valid.tabelKosong(TabModeMasterKFA);
    try{
        ps=koneksi.prepareStatement("select satu_sehat_kfa_master.name ,satu_sehat_kfa_master.kfa_code,"+
                "satu_sehat_kfa_master.active ,satu_sehat_kfa_master.state ,satu_sehat_kfa_master.image ,satu_sehat_kfa_master.updated_at,"
                + "satu_sehat_kfa_master.produksi_buatan ,satu_sehat_kfa_master.nie ,satu_sehat_kfa_master.nama_dagang ,"
                + "satu_sehat_kfa_master.manufacturer ,satu_sehat_kfa_master.registrar ,satu_sehat_kfa_master.generik ,"
                + "satu_sehat_kfa_master.rxterm ,satu_sehat_kfa_master.dose_per_unit ,satu_sehat_kfa_master.fix_price ,"
                + "satu_sehat_kfa_master.het_price ,satu_sehat_kfa_master.farmalkes_hscode ,satu_sehat_kfa_master.tayang_lkpp ,"
                + "satu_sehat_kfa_master.kode_lkpp ,satu_sehat_kfa_master.net_weight ,satu_sehat_kfa_master.net_weight_uom_name ,"
                + "satu_sehat_kfa_master.volume ,satu_sehat_kfa_master.volume_uom_name ,satu_sehat_kfa_master.dosage_form_code ,"
                + "satu_sehat_kfa_master.dosage_form_name ,satu_sehat_kfa_master.product_template_kfa_code ,"
                + "satu_sehat_kfa_master.product_template_name ,satu_sehat_kfa_master.product_template_state ,"
                + "satu_sehat_kfa_master.product_template_active ,satu_sehat_kfa_master.product_template_display_name ,"
                + "satu_sehat_kfa_master.product_template_updated_at from satu_sehat_kfa_master where satu_sehat_kfa_master.name like ? or "
                + "satu_sehat_kfa_master.kfa_code like ? or satu_sehat_kfa_master.produksi_buatan like ? or satu_sehat_kfa_master.nama_dagang like ? or "
                + "satu_sehat_kfa_master.manufacturer like ? order by satu_sehat_kfa_master.name");
        try{
            if(!TCari.getText().equals("")){
                    ps.setString(1,"%"+TCari.getText()+"%");
                    ps.setString(2,"%"+TCari.getText()+"%");
                    ps.setString(3,"%"+TCari.getText()+"%");
                    ps.setString(4,"%"+TCari.getText()+"%");
                    ps.setString(5,"%"+TCari.getText()+"%");
            }
            rs=ps.executeQuery();
            while(rs.next()){
                TabModeMasterKFA.addRow(new Object[]{
                    rs.getString("name"),rs.getString("kfa_code"),rs.getString("updated_at"),rs.getString("produksi_buatan"),rs.getString("nama_dagang"),
                    rs.getString("manufacturer")
                });
            }
        }catch (Exception e) {
            System.out.println("Notif Ketersediaan : "+e);
        } finally{
            if(rs!=null){
                rs.close();
            }
            if(ps!=null){
                ps.close();
            }
        }
    }catch (Exception e) {
        System.out.println("Notifikasi : "+e);
    }
        LCount.setText(""+TabModeMasterKFA.getRowCount());
}
    
