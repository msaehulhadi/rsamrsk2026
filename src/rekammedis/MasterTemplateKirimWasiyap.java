    private void tampil() {
        Valid.tabelKosong(tabMode);
        //render ulang table warna
        tbDokter.setDefaultRenderer(Object.class, new WarnaTableWA());
        try{
            ps=koneksi.prepareStatement(
                    "select template_pesan_wa.no_template,template_pesan_wa.nama_template,"+
                    "template_pesan_wa.isi_template "+
                    "from template_pesan_wa "+
                    (TCari.getText().equals("")?"":"where template_pesan_wa.no_template like ? or template_pesan_wa.nama_template like ? or "+
                    "template_pesan_wa.isi_template like ? ")+
                    "order by template_pesan_wa.no_template");
            try {
                if(!TCari.getText().trim().equals("")){
                    ps.setString(1,"%"+TCari.getText().trim()+"%");
                    ps.setString(2,"%"+TCari.getText().trim()+"%");
                    ps.setString(3,"%"+TCari.getText().trim()+"%");
                }
                rs=ps.executeQuery();
                while(rs.next()){
                    tabMode.addRow(new Object[]{
                        rs.getString("no_template"),rs.getString("nama_template"),rs.getString("isi_template")
                        
                    });
                }
            } catch (Exception e) {
                System.out.println(e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            }
        }catch(Exception e){
            System.out.println("Notifikasi : "+e);
        }
        LCount.setText(""+tabMode.getRowCount());
    }

