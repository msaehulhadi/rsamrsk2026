    private void BtnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnSimpanActionPerformed
        if(TJp.getText().trim().equals("")||KwitansiRalan.getText().trim().equals("")||Nota1Ranap.getText().trim().equals("")||Nota2Ranap.getText().trim().equals("")||
            KwitansiRanap.getText().trim().equals("")||NotaApotek.getText().trim().equals("")||NotaLab.getText().trim().equals("")||NotaToko.getText().trim().equals("")){
            Valid.textKosong(TJp,"Semua field");
        }else if(tabMode.getRowCount()==0){
            if(Sequel.menyimpantf("set_nota","'"+TJp.getText()+"','"+KwitansiRalan.getText()+"','"+Nota1Ranap.getText()+"',"+
                "'"+Nota2Ranap.getText()+"','"+KwitansiRanap.getText()+"','"+NotaApotek.getText()+"','"+NotaLab.getText()+"','"+NotaToko.getText()+"'"," Set Remunerasi ")==true){
                tampil();
                emptTeks();
            }                
        }else if(tabMode.getRowCount()>0){
            JOptionPane.showMessageDialog(null,"Maaf, Hanya diijinkan satu Set Nota, Kwitansi, Verifikasi Penjualan...!!!!");
            TJp.requestFocus();
        }
}//GEN-LAST:event_BtnSimpanActionPerformed

