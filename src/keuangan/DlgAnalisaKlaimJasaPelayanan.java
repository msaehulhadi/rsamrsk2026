    private void tampil() {
        Valid.tabelKosong(tabMode);
        try{
            ps=koneksi.prepareStatement(
                    "select eklaim_txt_detail.SEP,eklaim_txt_detail.NAMA_PASIEN,eklaim_txt_detail.DPJP,eklaim_txt_detail.INACBG,eklaim_txt_detail.DESKRIPSI_INACBG,eklaim_txt_detail.TOTAL_TARIF,eklaim_txt_detail.TARIF_RS "+
                    "from eklaim_txt_detail where eklaim_txt_detail.DISCHARGE_DATE between ? and ? and eklaim_txt_detail.dpjp like ? order by eklaim_txt_detail.SEP");
            try {
                ps.setString(1,Valid.SetTgl(Tgl1.getSelectedItem()+""));
                ps.setString(2,Valid.SetTgl(Tgl2.getSelectedItem()+""));
                ps.setString(3,"%"+TCari.getText().trim()+"%");
                rs=ps.executeQuery();
                while(rs.next()){
//                    rj.setText(Sequel.cariIsi("select count(SEP) from eklaim_txt_detail where DISCHARGE_DATE between '"+Valid.SetTgl(Tgl1.getSelectedItem()+"")+"' and '"+Valid.SetTgl(Tgl2.getSelectedItem()+"")+"' and dpjp like '%"+TCari.getText().trim()+"%' and ptd='2'"));
//                    ri.setText(Sequel.cariIsi("select count(SEP) from eklaim_txt_detail where DISCHARGE_DATE between '"+Valid.SetTgl(Tgl1.getSelectedItem()+"")+"' and '"+Valid.SetTgl(Tgl2.getSelectedItem()+"")+"' and dpjp like '%"+TCari.getText().trim()+"%' and ptd='1'"));
                    Integer CekBAHV=Sequel.cariInteger("select count(no_sep) from bahv_bpjs where no_sep='"+rs.getString("SEP")+"'");
                    String Keterangan="";
                    if(CekBAHV>0){
                        Keterangan="Terverifikasi BPJS";
                    }else{
                        Keterangan="Pending BPJS";
                    }
                    tabMode.addRow(new Object[]{
                        false,rs.getString("SEP"),rs.getString("NAMA_PASIEN"),rs.getString("DPJP"),rs.getString("INACBG"),rs.getString("DESKRIPSI_INACBG"),Valid.SetAngka(rs.getString("TOTAL_TARIF")),Valid.SetAngka(rs.getString("TARIF_RS")),Keterangan
                    });
                }
            } catch (Exception e) {
                System.out.println(e);
            } finally{
                if(rs!=null){
                    rs.close();
                }
                if(ps!=null){
                    ps.close();
                }
            }
        }catch(Exception e){
            System.out.println("Notifikasi : "+e);
        }
        LCount.setText(""+tabMode.getRowCount());
    }
    
    private void isForm(){
        if(ChkInput.isSelected()==true){
            ChkInput.setVisible(false);
            PanelInput.setPreferredSize(new Dimension(WIDTH,90));
            FormInput.setVisible(true);      
            ChkInput.setVisible(true);
        }else if(ChkInput.isSelected()==false){           
            ChkInput.setVisible(false);            
            PanelInput.setPreferredSize(new Dimension(WIDTH,20));
            FormInput.setVisible(false);      
            ChkInput.setVisible(true);
        }
    }
    
